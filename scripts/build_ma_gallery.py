"""Build the plain-file Ma review page from saved renders and human-editable reviews."""
import html
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1] / 'Ma'
reviews = json.loads((root / 'reviews.json').read_text(encoding='utf-8'))
cards = []
creative_ids = {f'M{i:02}' for i in range(8, 16)}
def order(folder):
    record = folder / 'render.json'
    ident = json.loads(record.read_text())['id'] if record.exists() else ''
    return (ident not in creative_ids, reviews.get(folder.name, {}).get('status') != 'shortlist', folder.name)

for folder in sorted((root / 'stills').iterdir(), key=order):
    if not (folder / 'render.json').exists():
        continue
    data = json.loads((folder / 'render.json').read_text(encoding='utf-8'))
    review = reviews.get(folder.name, {'status': 'unreviewed', 'notes': 'Awaiting close visual review.'})
    esc = html.escape
    url = 'stills/' + folder.name
    status = review['status']
    cards.append(f'''<article class="{esc(status)}">
<div class="label">{esc(status.upper())} <span>{esc(data['model'])} / {esc(data['id'])}</span></div>
<a href="{url}/master.png" target="_blank"><img src="{url}/wall.png" alt="{esc(data['title'])}" loading="lazy" width="1248" height="540"></a>
<div class="body"><h2>{esc(data['title'])}</h2><p>{esc(review['notes'])}</p>
<p class="meta">Seed {data['seed']} / {data['steps']} steps / {data['seconds']:.0f}s</p>
<p><a href="{url}/master.png">Master PNG + workflow</a> &nbsp; <a href="{url}/wall.png">Wall PNG</a> &nbsp; <a href="{url}/render.json">Exact settings</a></p>
<details><summary>Read / copy prompt</summary><h3>Positive</h3><pre>{esc(data['positive'])}</pre><h3>Negative</h3><pre>{esc(data['negative'])}</pre></details></div></article>''')
page = '''<!doctype html>
<!-- Generated by scripts/build_ma_gallery.py. Edit prompts/reviews, then rebuild. -->
<html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Ma Durga | Image review</title><style>
*{box-sizing:border-box}body{margin:0;background:#10100f;color:#eee8dc;font:16px/1.55 system-ui,sans-serif}header,main{max-width:1500px;margin:auto;padding:28px}header{padding-bottom:0}h1{font-size:38px;margin:0 0 12px}h2{font-size:19px;margin:0 0 8px}h3{font-size:15px}p{margin:8px 0 16px}a{color:#efca7e;text-underline-offset:3px}main{display:grid;grid-template-columns:repeat(2,minmax(0,1fr));gap:24px}article{border:1px solid #464239;border-radius:8px;overflow:hidden;background:#1b1b19}.shortlist{border-color:#cfaf6c}.label{padding:12px 16px;color:#d6c29c;font-size:12px;letter-spacing:.08em;display:flex;justify-content:space-between;gap:10px}.label span{color:#aaa;letter-spacing:0}img{display:block;width:100%;height:auto;background:#080808}.body{padding:18px}.meta{font-size:13px;color:#b5b0a5}summary{cursor:pointer;color:#efca7e}pre{white-space:pre-wrap;font:14px/1.6 system-ui;overflow-wrap:anywhere}@media(max-width:850px){main{grid-template-columns:1fr}header,main{padding:20px}h1{font-size:30px}}
</style><header><p class="meta">DURGA 2026 / GOLDEN GLAMOUR</p><h1>Ma Durga, closer look</h1>
<p>The new creative batch comes first: glass, chrome, woodcut, porcelain and other material studies. These are 2D images, including the sculpture looks. Traditional portraits and earlier experiments follow. Shortlist means worth discussing, not approved for the show. Click any image to inspect the full master.</p>
<p><a href="README.md">Workflow guide and depiction sources</a> &nbsp; <a href="prompts.json">Editable prompts</a> &nbsp; <a href="qwen-creative.json">Creative Qwen workflow</a> &nbsp; <a href="z-image.json">Z-Image comparison</a></p></header><main>'''
(root / 'index.html').write_text(page + '\n'.join(cards) + '</main></html>\n', encoding='utf-8')
print('Built Ma gallery:', len(cards), 'images')
